// 学習中の「切り上げ時間」＝ここまで考えて分からなければ解答を見る、という目安（アラーム）。
// 記録用の計測（timer.ts）とは別物である。timer.ts の上限は「その計測を捨てるか」の判定で、
// こちらは「解くのをやめて解答へ進むか」の判定なので、根拠も値も分けている。
//
// ── なぜ必要か
// この学習者の制約は時間の希少性そのもの（docs/design/study-time-scarcity.md）。
// 解けない1問に15分沈めると、その日の学習がその1問で終わる。過去問学習の定石も
// 「解法が思いつかなければすぐ解答を見て、解き方を覚えて類題に移る」であり、
// 粘る時間を伸ばしても得点は増えない。
//
// ── 何を基準に決めるか（3案の比較）
//  (a) 一律5分         : 実装は最小だが、1分で解ける暗記問題にも5分待たせる。鳴っても情報が無い。
//  (b) 本番の持ち時間  : A問題5分・B問題10分（examTime.ts）。本番基準としては正しいが、
//                        これは「合格者が本番で使ってよい上限」であって、学習中に粘ってよい
//                        時間ではない。難易度1の暗記問題まで5分になる。
//  (c) 自分の実測 × 係数（採用）: estimateMinutes の推定（①その問題自身の直近の実測 →
//                        ②難易度×studyMode の中央値 → ③既定値×ステータス係数）を基準に、
//                        余裕をみて 1.5 倍したところで鳴らす。
//
// (c) を採る。理由は、切り上げの判断に必要なのは「絶対的な長さ」ではなく
// 「自分にとって、この問題に想定外の時間がかかり始めたか」だから。推定はすでに問題ごとに
// 出ており（暗記1.5分／難易度2の計算5.5分など）、新しい基準を別に持ち込むと、時間予算の
// 見積もりと切り上げが別々の時間観で動くことになる。
//
// ── 係数を 1.5 にした理由
// 1.0 だと推定どおりに解けている最中でも半数近くで鳴り、アラームが雑音になる。
// 2.0 だと難易度2の計算問題で11分となり、本番の持ち時間を大きく超えて切り上げの意味を失う。
// 1.5 は「順調なら鳴らない／詰まったら鳴る」の境目で、難易度2の計算問題（推定5.5分）で
// 8.25分 → 上限で5分に収まる。
//
// ── 上下限
// 上限は本番の持ち時間（A問題5分・B問題10分）。本番で解ききれない時間をかけている以上、
// 学習でそれ以上粘っても本番の得点には結びつかない。
// 下限は90秒。推定が短い問題（暗記・A/S判定済み）で30秒アラームが鳴ると、
// 思い出しかけた手を止めてしまう。想起には最低限の時間が要る。
//
// 純ロジックのみ。DB・UI・音には依存しない。

import { examTimeLimitSeconds } from './examTime'

// 推定所要時間に掛ける倍率。詳細は上のコメント。
export const CUTOFF_FACTOR = 1.5

// 切り上げ時間の下限（秒）。これより短くは鳴らさない。
export const CUTOFF_MIN_SECONDS = 90

// 切り上げ秒。title は出典表記から A問題／B問題を判定するために使う（examTime.ts）。
// estimatedMinutes は estimateMinutes() の戻り値（分・小数）。
export function cutoffSeconds(title: string, estimatedMinutes: number): number {
  const limit = examTimeLimitSeconds(title)
  const raw = Math.round(estimatedMinutes * 60 * CUTOFF_FACTOR)
  // 下限→上限の順に適用する。上限のほうが常に下限以上（A問題300秒 > 90秒）なので、
  // どちらの制約も満たす値になる。
  return Math.min(Math.max(raw, CUTOFF_MIN_SECONDS), limit)
}

// 経過表示は "3:07" 形式（本番CBTの残り時間表示と同じ読み方に揃える）。
// 60分以上は "1:02:03"。学習1問でそこまで行くことはないが、一時停止したまま
// 放置した場合に "62:03" と出るより読み違えにくい。
export function formatClock(totalSeconds: number): string {
  const sec = Math.max(0, Math.floor(totalSeconds))
  const s = String(sec % 60).padStart(2, '0')
  const m = Math.floor(sec / 60)
  if (m < 60) return `${m}:${s}`
  return `${Math.floor(m / 60)}:${String(m % 60).padStart(2, '0')}:${s}`
}
