-- 年度別ペーパーの表示座標（questionStartPct / answerYPct / explanationEndPct）を
-- Supabase 側へ移し、以後 denken_question_assets を唯一の正とする
-- （docs/data-correction-workflow.md §5-A）。
--
-- これまで年度別の座標は src/data/denken3/*/papers/*.ts に直書きされ、
-- 表示側（PaperImage）はそのTS値だけを見ていた。そのため
--   - 値を1つ直すのに「TS編集 → commit → PR → デプロイ」が必要（①）
--   - answer_y_pct は取り込み時にDBへ書かれるが誰も読まない死んだ列だった（③）
-- 本マイグレーションで3座標をDBに揃え、修正を「SQL 1行のUPDATE」で完結させる。
--
-- 方針は migration 008 と同じく既存カラム・制約を変更せず ADD COLUMN のみ。
-- 既定値は PaperQuestion の既定（切り捨てなし）に合わせる:
--   question_start_pct  = 0   … 上端から表示（【難易度】行より上を切らない）
--   explanation_end_pct = 100 … 下端まで表示（末尾の宣伝バナー等を切らない）
ALTER TABLE denken_question_assets
  ADD COLUMN IF NOT EXISTS question_start_pct  NUMERIC NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS explanation_end_pct NUMERIC NOT NULL DEFAULT 100;

