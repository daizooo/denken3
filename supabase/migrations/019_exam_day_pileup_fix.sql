-- 試験当日に張り付いた復習予定を、各カード自身の忘却曲線に基づく日付へ移すデータ是正。
-- 012 / 013 / 015 と同じ「既存データの誤りを直す」形のマイグレーション。
--
-- ■ 何が起きていたか（2026-09-04 の実測）
-- 学習済み FSRS パラメータ（版4）の採用で復習間隔が伸びた結果、232カード中
-- **58件（25%）の due_date がちょうど試験日 2027-02-06 に張り付いた。**
--
-- 原因は clipDueToExam が maxInterval = daysToExam としていたことで、間隔が残日数以上の
-- カードは全て試験日ちょうどへ丸められていた。これは2つの意味で成立していない。
--   ① 試験当日は受験する日であって、復習日にならない。消化できない予定である。
--   ② 試験日は 分野別 の地平ではない。この枠組みは 分野別 の主軸期間を
--      bunya_target_date（実データ 2026-11-29）までとし、その後は nendo_start_date
--      （同 11-30）から年度別演習が主軸になると定めている。
--
-- ■ どこへ動かすか ―― 固定日ではなく、各カードの忘却曲線で決める
-- 当初は S と同じ最終確認（試験21日前 = 2027-01-16）へ集約する案だったが、それは誤り。
-- finalCheckDue は固定値であって FSRS の出力ではなく、**58件を1日へ潰してしまう**。
-- 実測では、この58件の素の予定日は「試験当日」から「試験の224日後」まで224日の幅がある。
--
-- 代わりに、この枠組みが既に持つ直前期の基準（RETENTION_ENDGAME = 0.90）で引き直した。
-- 試験日時点の想起確率 R は58件とも 0.850〜0.902 に密集しており、枠組みが直前期に
-- 求める 0.90 を55件が下回る。その55件を「0.90 を割る日」に入れる。
--
-- 結果（適用前に全232カードを新ロジックで再生して確認済み）:
--   変化するのは 58件のみ。他174件は不変。試験当日に残るカードは 0件。
--   55件が **22日へ分散**（同一日の最大10件）。月別 10月:3 / 11月:23 / 12月:12 / 1月:16 / 2月:1
--   3件は R(試験日) >= 0.90 を満たすため試験後の日付になる（＝試験までは復習不要）。
--
-- ■ コード側との一致
-- 同じ是正は fsrs.ts の applyExamHorizon が恒久的に行う。このマイグレーションは
-- **既に書き込まれてしまった行**を追いつかせるためのもの。試験日に張り付いたカードは
-- その日まで復習されないので、放置すると次回レビューでの自然な再計算が永久に起きない。
-- 下の値は同じコードで算出しており、適用後は履歴の再生結果と DB の値が一致する。
--
-- 現在 2027-02-06 の行だけを対象にするので、再実行しても二重には効かない。

